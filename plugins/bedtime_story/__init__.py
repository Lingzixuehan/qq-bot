def is_bedtime_available() -> bool:
    """检查当前是否在睡前故事可用时间段（21:00-03:00）"""
    hour = datetime.now().hour
    # 21:00-23:59 或 00:00-03:00
    return hour >= AVAILABLE_START_HOUR or hour < AVAILABLE_END_HOUR


def get_random_story(group_id: str) -> str:
    """
    获取一个随机的睡前故事，避免短期内重复

    Args:
        group_id: 群组ID

    Returns:
        随机选择的故事文本
    """
    # 获取或创建该群的历史记录
    if group_id not in recent_stories:
        recent_stories[group_id] = deque(maxlen=MAX_RECENT_STORIES)

    recent = recent_stories[group_id]

    # 获取可用的故事索引（排除最近使用的）
    available_indices = [i for i in range(len(BEDTIME_STORIES)) if i not in recent]

    # 如果所有故事都用过了（不太可能，因为有15个故事），就清空历史
    if not available_indices:
        recent.clear()
        available_indices = list(range(len(BEDTIME_STORIES)))

    # 随机选择一个故事
    selected_index = random.choice(available_indices)

    # 记录使用过的故事
    recent.append(selected_index)

    logger.info(f"群 {group_id} 选择了故事 {selected_index}，最近使用: {list(recent)}")

    return BEDTIME_STORIES[selected_index]


# ============== 命令处理 ==============
bedtime_story = on_command("睡前故事", aliases={"讲故事", "晚安故事"}, priority=5, block=True)


@bedtime_story.handle()
async def handle_bedtime_story(event: GroupMessageEvent):
    """处理睡前故事命令"""
    group_id = str(event.group_id)

    # 检查时间
    if not is_bedtime_available():
        current_hour = datetime.now().hour
        await bedtime_story.finish(
            f"😴 睡前故事只在晚上9点到凌晨3点开放哦~\n"
            f"⏰ 现在是 {current_hour} 点，还不到睡觉时间呢！"
        )

    # 获取随机故事
    story = get_random_story(group_id)

    # 发送故事
    message = f"✨ 睡前故事时间 ✨\n\n{story}"

    await bedtime_story.finish(message)
